# Parameter validation and mocked TMSL tests live in test/Unit/SsasCommands.Tests.ps1.
BeforeDiscovery {
    . (Join-Path -Path (Split-Path -Parent $PSScriptRoot) -ChildPath 'TestHelpers.ps1')
    $skipIntegration = -not (Test-DeployCubeIntegrationEnabled)
}

BeforeAll {
    . (Join-Path -Path (Split-Path -Parent $PSScriptRoot) -ChildPath 'TestHelpers.ps1')
    Import-DeployCubeForTest
    $Settings = Get-DeployCubeIntegrationSettings
    $SavedErrorActionPreference = $global:ErrorActionPreference
}

AfterAll {
    foreach ($cube in @('CubeWithInvalidDataSource', 'CubeToProcess')) {
        try { Unpublish-Cube -Server $Settings.Server -CubeDatabase $cube } catch { Write-Warning "Cleanup of $cube failed: $_" }
    }
    $global:ErrorActionPreference = $SavedErrorActionPreference
}

Describe "Invoke-ProcessTabularCubeDatabase" -Tag 'Integration', 'SSAS', 'Round2' -Skip:$skipIntegration {
    BeforeAll {
        Initialize-DeployCubeIntegrationBaseline
    }

    Context 'Invalid inputs' {
        It 'Process NonExistantServer should Throw' {
            # Need to capture the error output generated by Invoke-AsCmd
            { $msg = Invoke-ProcessTabularCubeDatabase -Server 'NonExistantServer' -CubeDatabase 'NonExistantCube' 2>&1 } | Should -Throw;
        }
        It 'Process NonExistantCube should Throw' {
            { Invoke-ProcessTabularCubeDatabase -Server $Settings.Server -CubeDatabase 'NonExistantCube' } | Should -Throw;
        }

        It 'Process cube with invalid data source should throw' {
            $CubeDatabase = 'CubeWithInvalidDataSource';
            { Publish-Cube -AsDatabasePath $Settings.AsDatabasePath1200 -Server $Settings.Server -CubeDatabase $CubeDatabase; } | Should -Not -Throw;
            { Update-TabularCubeDataSource -Server $Settings.Server -CubeDatabase $CubeDatabase -SourceSqlServer $Settings.SourceSqlServer -SourceSqlDatabase 'NonExistantDB' -ImpersonationMode 'ImpersonateServiceAccount'; } | Should -Not -Throw;
            { Invoke-ProcessTabularCubeDatabase -Server $Settings.Server -CubeDatabase $CubeDatabase -RefreshType Full } | Should -Throw;
            { Unpublish-Cube -Server $Settings.Server -CubeDatabase $CubeDatabase; } | Should -Not -Throw;
        }
    }

    Context 'Valid input' {
        It 'Process cube correctly' {
            $CubeDatabase = 'CubeToProcess';
            { Publish-Cube -AsDatabasePath $Settings.AsDatabasePath1200 -Server $Settings.Server -CubeDatabase $CubeDatabase; } | Should -Not -Throw;
            { Update-TabularCubeDataSource -Server $Settings.Server -CubeDatabase $CubeDatabase -SourceSqlServer $Settings.SourceSqlServer -SourceSqlDatabase $Settings.SourceSqlDatabase -ImpersonationMode 'ImpersonateServiceAccount'; } | Should -Not -Throw;
            { Invoke-ProcessTabularCubeDatabase -Server $Settings.Server -CubeDatabase $CubeDatabase -RefreshType Full } | Should -Not -Throw;
            { Unpublish-Cube -Server $Settings.Server -CubeDatabase $CubeDatabase; } | Should -Not -Throw;
        }
    }
}
